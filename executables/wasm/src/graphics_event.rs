//! Xila's guest event contract, independent of LVGL's native discriminants.
//! Keep the event order stable; translate at the host boundary.

#[repr(C)]
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum EventCode {
    All = 0,
    Pressed,
    Pressing,
    PressLost,
    ShortClicked,
    SingleClicked,
    DoubleClicked,
    TripleClicked,
    LongPressed,
    LongPressedRepeat,
    Clicked,
    Released,
    ScrollBegin,
    ScrollThrowBegin,
    ScrollEnd,
    Scroll,
    Gesture,
    Key,
    Rotary,
    Focused,
    Defocused,
    Leave,
    HitTest,
    IndevReset,
    HoverOver,
    HoverLeave,
    CoverCheck,
    RefreshExtDrawSize,
    DrawMainBegin,
    DrawMain,
    DrawMainEnd,
    DrawPostBegin,
    DrawPost,
    DrawPostEnd,
    DrawTaskAdded,
    ValueChanged,
    Insert,
    Refresh,
    Ready,
    Cancel,
    Create,
    Delete,
    ChildChanged,
    ChildCreated,
    ChildDeleted,
    ScreenUnloadStart,
    ScreenLoadStart,
    ScreenLoaded,
    ScreenUnloaded,
    SizeChanged,
    StyleChanged,
    LayoutChanged,
    GetSelfSize,
    InvalidateArea,
    ResolutionChanged,
    ColorFormatChanged,
    RefreshRequest,
    RefreshStart,
    RefreshReady,
    RenderStart,
    RenderReady,
    FlushStart,
    FlushFinish,
    FlushWaitStart,
    FlushWaitFinish,
    Vsync,
    VsyncRequest,
    Last,
    Preprocess = 0x8000,
    MarkedDeleting = 0x10000,
}

/// Xila window close request, separate from LVGL's standard events.
pub const EVENT_CLOSE_REQUESTED: u32 = EventCode::Last as u32 + 3;
